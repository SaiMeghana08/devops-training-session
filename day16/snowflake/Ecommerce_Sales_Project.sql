    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY
FROM CUSTOMERS
WHERE (CUSTOMER_NAME IS NOT NULL AND TRIM(CUSTOMER_NAME) = '')
   OR (CITY IS NOT NULL AND CITY <> TRIM(CITY));

SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    NULLIF(TRIM(CUSTOMER_NAME), '') AS CLEANED_NAME
FROM CUSTOMERS;


CREATE OR REPLACE TABLE CUSTOMERS_CLEANED AS
SELECT
    CUSTOMER_ID,
    NULLIF(TRIM(CUSTOMER_NAME), '') AS CUSTOMER_NAME,
    NULLIF(TRIM(CITY), '') AS CITY,
    NULLIF(TRIM(CUSTOMER_TYPE), '') AS CUSTOMER_TYPE,
    NULLIF(TRIM(EMAIL), '') AS EMAIL
FROM CUSTOMERS;

SELECT *
FROM CUSTOMERS_CLEANED
WHERE CUSTOMER_ID = 'C007';

CREATE OR REPLACE TABLE ORDERS_CLEANED AS
SELECT
    ORDER_ID,
    NULLIF(TRIM(CUSTOMER_ID), '') AS CUSTOMER_ID,
    ORDER_DATE,
    NULLIF(TRIM(PRODUCT), '') AS PRODUCT,
    QUANTITY,
    UNIT_PRICE,
    NULLIF(TRIM(LOCATION), '') AS LOCATION
FROM ORDERS;


SELECT
    ORDER_ID,
    LOCATION
FROM ORDERS_CLEANED
WHERE ORDER_ID = 2016;


SELECT
    (SELECT COUNT(*) FROM CUSTOMERS) AS ORIGINAL_CUSTOMERS,
    (SELECT COUNT(*) FROM CUSTOMERS_CLEANED) AS CLEANED_CUSTOMERS,
    (SELECT COUNT(*) FROM ORDERS) AS ORIGINAL_ORDERS,
    (SELECT COUNT(*) FROM ORDERS_CLEANED) AS CLEANED_ORDERS;

SELECT
    ORDER_ID,
    CUSTOMER_ID,
    ORDER_DATE,
    PRODUCT,
    QUANTITY,
    UNIT_PRICE,
    LOCATION,
    ROW_NUMBER() OVER (
        PARTITION BY ORDER_ID
        ORDER BY ORDER_ID
    ) AS ROW_NUM
FROM ORDERS_CLEANED;

CREATE OR REPLACE TABLE ORDERS_DEDUPED AS
SELECT
    ORDER_ID,
    CUSTOMER_ID,
    ORDER_DATE,
    PRODUCT,
    QUANTITY,
    UNIT_PRICE,
    LOCATION
FROM ORDERS_CLEANED
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY ORDER_ID
    ORDER BY ORDER_ID
) = 1; 



