SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    CUSTOMER_TYPE,
    EMAIL
FROM CUSTOMERS
WHERE CUSTOMER_NAME IS NULL
   OR CITY IS NULL
   OR CUSTOMER_TYPE IS NULL
   OR EMAIL IS NULL;


SELECT
    COUNT_IF(CUSTOMER_ID IS NULL) AS MISSING_CUSTOMER_ID,
    COUNT_IF(CUSTOMER_NAME IS NULL) AS MISSING_CUSTOMER_NAME,
    COUNT_IF(CITY IS NULL) AS MISSING_CITY,
    COUNT_IF(CUSTOMER_TYPE IS NULL) AS MISSING_CUSTOMER_TYPE,
    COUNT_IF(EMAIL IS NULL) AS MISSING_EMAIL
FROM CUSTOMERS;

SELECT
    COUNT_IF(ORDER_ID IS NULL) AS MISSING_ORDER_ID,
    COUNT_IF(CUSTOMER_ID IS NULL) AS MISSING_CUSTOMER_ID,
    COUNT_IF(ORDER_DATE IS NULL) AS MISSING_ORDER_DATE,
    COUNT_IF(PRODUCT IS NULL) AS MISSING_PRODUCT,
    COUNT_IF(QUANTITY IS NULL) AS MISSING_QUANTITY,
    COUNT_IF(UNIT_PRICE IS NULL) AS MISSING_UNIT_PRICE,
    COUNT_IF(LOCATION IS NULL) AS MISSING_LOCATION
FROM ORDERS;


SELECT
    ORDER_ID,
    COUNT(*) AS RECORD_COUNT
FROM ORDERS
GROUP BY ORDER_ID
HAVING COUNT(*) > 1;

SELECT *
FROM ORDERS
WHERE ORDER_ID IN (
    SELECT ORDER_ID
    FROM ORDERS
    GROUP BY ORDER_ID
    HAVING COUNT(*) > 1
)
ORDER BY ORDER_ID;

SELECT
    O.ORDER_ID,
    O.CUSTOMER_ID,
    O.PRODUCT,
    O.QUANTITY,
    O.UNIT_PRICE
FROM ORDERS O
LEFT JOIN CUSTOMERS C
    ON O.CUSTOMER_ID = C.CUSTOMER_ID
WHERE C.CUSTOMER_ID IS NULL;


SELECT
    CUSTOMER_ID,
    CITY AS ORIGINAL_CITY,
    TRIM(CITY) AS CLEANED_CITY
FROM CUSTOMERS
WHERE CITY IS NOT NULL
  AND CITY <> TRIM(CITY);


  SELECT
    ORDER_ID,
    LOCATION AS ORIGINAL_LOCATION,
    TRIM(LOCATION) AS CLEANED_LOCATION
FROM ORDERS
WHERE LOCATION IS NOT NULL
  AND LOCATION <> TRIM(LOCATION);

SELECT *
