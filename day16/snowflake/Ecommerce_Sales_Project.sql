SELECT
    TRIM(LOCATION) AS LOCATION,
    COUNT(*) AS TOTAL_ORDERS
FROM ORDERS
WHERE LOCATION IS NOT NULL
GROUP BY TRIM(LOCATION)
ORDER BY TOTAL_ORDERS DESC;

SELECT
    SUM(QUANTITY * UNIT_PRICE) AS TOTAL_REVENUE
FROM ORDERS;


SELECT
    TRIM(LOCATION) AS LOCATION,
    SUM(QUANTITY * UNIT_PRICE) AS TOTAL_REVENUE
FROM ORDERS
WHERE LOCATION IS NOT NULL
GROUP BY TRIM(LOCATION)
ORDER BY TOTAL_REVENUE DESC;

SELECT
    PRODUCT,
    SUM(QUANTITY) AS TOTAL_QUANTITY_SOLD
FROM ORDERS
WHERE PRODUCT IS NOT NULL
GROUP BY PRODUCT
ORDER BY TOTAL_QUANTITY_SOLD DESC;

SELECT
    PRODUCT,
    SUM(QUANTITY * UNIT_PRICE) AS TOTAL_REVENUE
FROM ORDERS
WHERE PRODUCT IS NOT NULL
GROUP BY PRODUCT
ORDER BY TOTAL_REVENUE DESC;

SELECT
    COUNT(*) AS TOTAL_ORDER_RECORDS,
    COUNT(QUANTITY * UNIT_PRICE) AS ORDERS_WITH_CALCULABLE_REVENUE,
    AVG(QUANTITY * UNIT_PRICE) AS AVERAGE_ORDER_VALUE
FROM ORDERS;

SELECT
    ORDER_ID,
    PRODUCT,
    QUANTITY,
    UNIT_PRICE,
    QUANTITY * UNIT_PRICE AS ORDER_REVENUE
FROM ORDERS
WHERE QUANTITY IS NULL
   OR UNIT_PRICE IS NULL;


SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    O.ORDER_ID,
    O.PRODUCT,
    O.QUANTITY,
    O.UNIT_PRICE
FROM CUSTOMERS C
INNER JOIN ORDERS O
    ON C.CUSTOMER_ID = O.CUSTOMER_ID
ORDER BY O.ORDER_ID;


SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    O.ORDER_ID,
    O.PRODUCT
FROM CUSTOMERS C
LEFT JOIN ORDERS O
    ON C.CUSTOMER_ID = O.CUSTOMER_ID
ORDER BY C.CUSTOMER_ID, O.ORDER_ID;


SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    O.ORDER_ID,
    O.PRODUCT,
    O.QUANTITY
FROM CUSTOMERS C
RIGHT JOIN ORDERS O
    ON C.CUSTOMER_ID = O.CUSTOMER_ID
ORDER BY O.ORDER_ID;


SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    SUM(O.QUANTITY * O.UNIT_PRICE) AS TOTAL_REVENUE
FROM CUSTOMERS C
INNER JOIN ORDERS O
    ON C.CUSTOMER_ID = O.CUSTOMER_ID
GROUP BY
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME
ORDER BY TOTAL_REVENUE DESC;


SELECT
    C.CUSTOMER_TYPE,
    COUNT(O.ORDER_ID) AS TOTAL_ORDERS,
    SUM(O.QUANTITY * O.UNIT_PRICE) AS TOTAL_REVENUE
FROM CUSTOMERS C
INNER JOIN ORDERS O
    ON C.CUSTOMER_ID = O.CUSTOMER_ID
GROUP BY C.CUSTOMER_TYPE
ORDER BY TOTAL_REVENUE DESC;

SELECT
    O.ORDER_ID,
    O.CUSTOMER_ID,
    C.CUSTOMER_NAME
FROM ORDERS O
LEFT JOIN CUSTOMERS C
    ON O.CUSTOMER_ID = C.CUSTOMER_ID
WHERE C.CUSTOMER_NAME IS NULL;

