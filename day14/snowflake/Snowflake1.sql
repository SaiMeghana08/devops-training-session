CREATE DATABASE IF NOT EXISTS RETAIL_DB;
CREATE SCHEMA IF NOT EXISTS RETAIL_DB.RAW;

CREATE WAREHOUSE IF NOT EXISTS RETAIL_WH
WITH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;


USE WAREHOUSE RETAIL_WH;

CREATE TABLE IF NOT EXISTS RETAIL_DB.RAW.SALES (
    ORDER_ID NUMBER,
    PRODUCT VARCHAR(100),
    QUANTITY NUMBER,
    UNIT_PRICE NUMBER(10,2),
    CITY VARCHAR(100)
);


DESCRIBE TABLE RETAIL_DB.RAW.SALES;


CREATE STAGE IF NOT EXISTS RETAIL_STAGE
    FILE_FORMAT = RETAIL_CSV_FORMAT;

SHOW STAGES IN SCHEMA RETAIL_DB.RAW;


LIST @RETAIL_DB.RAW.RETAIL_STAGE;

COPY INTO RETAIL_DB.RAW.SALES
FROM @RETAIL_DB.RAW.RETAIL_STAGE
FILE_FORMAT = (FORMAT_NAME = 'RETAIL_DB.RAW.RETAIL_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

SELECT *
FROM RETAIL_DB.RAW.SALES
ORDER BY ORDER_ID;


CREATE FILE FORMAT IF NOT EXISTS RETAIL_CSV_FORMAT
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE;

DESC FILE FORMAT RETAIL_CSV_FORMAT;


SELECT
    ORDER_ID,
    COUNT(*) AS RECORD_COUNT
FROM RETAIL_DB.RAW.SALES
GROUP BY ORDER_ID
HAVING COUNT(*) > 1;


SELECT *
FROM RETAIL_DB.RAW.SALES
WHERE CITY IS NULL;

SELECT COUNT(*) AS MISSING_CITY_COUNT
FROM RETAIL_DB.RAW.SALES
WHERE CITY IS NULL;

SELECT *
FROM RETAIL_DB.RAW.SALES
WHERE ORDER_ID IN (1003, 1005)
ORDER BY ORDER_ID;

SELECT *,
       ROW_NUMBER() OVER (
           PARTITION BY ORDER_ID
           ORDER BY ORDER_ID
       ) AS ROW_NUM
FROM RETAIL_DB.RAW.SALES;



CREATE TABLE RETAIL_DB.RAW.SALES_BACKUP
CLONE RETAIL_DB.RAW.SALES;

DELETE FROM RETAIL_DB.RAW.SALES
USING (
    SELECT
        ORDER_ID,
        ROW_NUMBER() OVER (
            PARTITION BY ORDER_ID
            ORDER BY ORDER_ID
        ) AS ROW_NUM
    FROM RETAIL_DB.RAW.SALES
) AS DUPLICATES
WHERE SALES.ORDER_ID = DUPLICATES.ORDER_ID
AND DUPLICATES.ROW_NUM > 1;

SELECT *
FROM RETAIL_DB.RAW.SALES
ORDER BY ORDER_ID;


SELECT ORDER_ID, COUNT(*) AS RECORD_COUNT
FROM RETAIL_DB.RAW.SALES
GROUP BY ORDER_ID
HAVING COUNT(*) > 1;



CREATE TABLE RETAIL_DB.RAW.SALES_CLEAN AS
SELECT DISTINCT *
FROM RETAIL_DB.RAW.SALES;

SELECT *
FROM RETAIL_DB.RAW.SALES_CLEAN
ORDER BY ORDER_ID;

SELECT
    ORDER_ID,
    COUNT(*) AS RECORD_COUNT
FROM RETAIL_DB.RAW.SALES_CLEAN
GROUP BY ORDER_ID
HAVING COUNT(*) > 1;

SELECT *
FROM RETAIL_DB.RAW.SALES_CLEAN
WHERE CITY IS NULL OR CITY = '';


UPDATE RETAIL_DB.RAW.SALES_CLEAN
SET CITY = 'Unknown'
WHERE CITY IS NULL OR CITY = '';


SELECT *
FROM RETAIL_DB.RAW.SALES_CLEAN
WHERE ORDER_ID = 1012;



SELECT
    ORDER_ID,
    PRODUCT,
    QUANTITY,
    UNIT_PRICE,
    QUANTITY * UNIT_PRICE AS REVENUE
FROM RETAIL_DB.RAW.SALES_CLEAN
ORDER BY ORDER_ID;


SELECT
    SUM(QUANTITY * UNIT_PRICE) AS TOTAL_REVENUE
FROM RETAIL_DB.RAW.SALES_CLEAN;


SELECT
    AVG(QUANTITY * UNIT_PRICE) AS AVERAGE_REVENUE
FROM RETAIL_DB.RAW.SALES_CLEAN;


SELECT
    PRODUCT,
    SUM(QUANTITY) AS TOTAL_QUANTITY,
    SUM(QUANTITY * UNIT_PRICE) AS TOTAL_REVENUE
FROM RETAIL_DB.RAW.SALES_CLEAN
GROUP BY PRODUCT
ORDER BY TOTAL_REVENUE DESC;


SELECT
    CITY,
    COUNT(*) AS TOTAL_ORDERS,
    SUM(QUANTITY) AS TOTAL_QUANTITY,
    SUM(QUANTITY * UNIT_PRICE) AS TOTAL_REVENUE
FROM RETAIL_DB.RAW.SALES_CLEAN
GROUP BY CITY
ORDER BY TOTAL_REVENUE DESC;


SELECT
    CITY,
    SUM(QUANTITY * UNIT_PRICE) AS TOTAL_REVENUE
FROM RETAIL_DB.RAW.SALES_CLEAN
GROUP BY CITY
HAVING SUM(QUANTITY * UNIT_PRICE) > 10000;


SELECT
    PRODUCT,
    SUM(QUANTITY) AS TOTAL_QUANTITY
FROM RETAIL_DB.RAW.SALES_CLEAN
GROUP BY PRODUCT
HAVING SUM(QUANTITY) > 2;


