CREATE SCHEMA IF NOT EXISTS ANALYTICS_SH;
USE DATABASE PROJECT_DB;
USE SCHEMA ANALYTICS_SH;
USE WAREHOUSE ECOMMERCE_WH;

CREATE OR REPLACE VIEW SALES_ANALYTICS AS
SELECT
    O.ORDER_ID,
    O.ORDER_DATE,
    O.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.GENDER,
    C.AGE,
    O.CITY,
    O.PRODUCT_NAME,
    O.CATEGORY,
    O.QUANTITY,
    O.UNIT_PRICE,
    O.DISCOUNT_PERCENT,

    O.QUANTITY * O.UNIT_PRICE AS GROSS_REVENUE,

    O.QUANTITY * O.UNIT_PRICE
        * (O.DISCOUNT_PERCENT / 100) AS DISCOUNT_AMOUNT,

    O.QUANTITY * O.UNIT_PRICE
        * (1 - O.DISCOUNT_PERCENT / 100) AS NET_REVENUE

FROM PROJECT_DB.CLEANED.ORDERS O
INNER JOIN PROJECT_DB.CLEANED.CUSTOMERS C
    ON O.CUSTOMER_ID = C.CUSTOMER_ID;


CREATE OR REPLACE VIEW MONTHLY_SALES AS
SELECT
    DATE_TRUNC('MONTH', ORDER_DATE)::DATE AS SALES_MONTH,
    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
    SUM(QUANTITY) AS TOTAL_QUANTITY,
    SUM(GROSS_REVENUE) AS GROSS_REVENUE,
    SUM(DISCOUNT_AMOUNT) AS TOTAL_DISCOUNT,
    SUM(NET_REVENUE) AS NET_REVENUE
FROM SALES_ANALYTICS
GROUP BY DATE_TRUNC('MONTH', ORDER_DATE)::DATE;

CREATE OR REPLACE VIEW CATEGORY_SALES AS
SELECT
    CATEGORY,
    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
    SUM(QUANTITY) AS TOTAL_QUANTITY,
    SUM(NET_REVENUE) AS TOTAL_REVENUE
FROM SALES_ANALYTICS
GROUP BY CATEGORY;


CREATE OR REPLACE VIEW CITY_SALES AS
SELECT
    CITY,
    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
    COUNT(DISTINCT CUSTOMER_ID) AS TOTAL_CUSTOMERS,
    SUM(NET_REVENUE) AS TOTAL_REVENUE
FROM SALES_ANALYTICS
GROUP BY CITY;


CREATE OR REPLACE VIEW PRODUCT_SALES AS
SELECT
    PRODUCT_NAME,
    CATEGORY,
    SUM(QUANTITY) AS UNITS_SOLD,
    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
    SUM(NET_REVENUE) AS TOTAL_REVENUE
FROM SALES_ANALYTICS
GROUP BY PRODUCT_NAME, CATEGORY;


CREATE OR REPLACE VIEW CUSTOMER_SALES AS
SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    GENDER,
    AGE,
    CITY,
    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
    SUM(NET_REVENUE) AS TOTAL_REVENUE
FROM SALES_ANALYTICS
GROUP BY
    CUSTOMER_ID,
    CUSTOMER_NAME,
    GENDER,
    AGE,
    CITY;


SELECT
    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
    COUNT(DISTINCT CUSTOMER_ID) AS TOTAL_CUSTOMERS,
    SUM(QUANTITY) AS TOTAL_UNITS_SOLD,
    SUM(GROSS_REVENUE) AS GROSS_REVENUE,
    SUM(DISCOUNT_AMOUNT) AS TOTAL_DISCOUNT,
    SUM(NET_REVENUE) AS NET_REVENUE,
    AVG(NET_REVENUE) AS AVG_ORDER_VALUE
FROM SALES_ANALYTICS;

