CREATE OR REPLACE TABLE CUSTOMERS AS
SELECT
    TRIM(CUSTOMER_ID) AS CUSTOMER_ID,
    TRIM(CUSTOMER_NAME) AS CUSTOMER_NAME,
    TRIM(GENDER) AS GENDER,
    TRY_TO_NUMBER(AGE)::NUMBER(3,0) AS AGE,
    TRIM(CITY) AS CITY
FROM PROJECT_DB.STAGING.CUSTOMERS_RAW
WHERE CUSTOMER_ID IS NOT NULL
  AND TRIM(CUSTOMER_ID) <> ''
  AND CUSTOMER_NAME IS NOT NULL
  AND TRIM(CUSTOMER_NAME) <> ''
  AND GENDER IS NOT NULL
  AND TRIM(GENDER) <> ''
  AND TRY_TO_NUMBER(AGE) BETWEEN 1 AND 100
  AND CITY IS NOT NULL
  AND TRIM(CITY) <> ''
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY TRIM(CUSTOMER_ID)
    ORDER BY TRIM(CUSTOMER_ID)
) = 1;


CREATE OR REPLACE TABLE ORDERS AS
SELECT
    TRIM(O.ORDER_ID) AS ORDER_ID,
    TRIM(O.CUSTOMER_ID) AS CUSTOMER_ID,
    TRY_TO_DATE(TRIM(O.ORDER_DATE), 'YYYY-MM-DD') AS ORDER_DATE,
    TRIM(O.PRODUCT_NAME) AS PRODUCT_NAME,
    TRIM(O.CATEGORY) AS CATEGORY,
    TRY_TO_NUMBER(O.QUANTITY)::NUMBER(10,0) AS QUANTITY,
    TRY_TO_DECIMAL(O.UNIT_PRICE, 10, 2) AS UNIT_PRICE,
    TRY_TO_DECIMAL(O.DISCOUNT_PERCENT, 5, 2) AS DISCOUNT_PERCENT,
    TRIM(O.CITY) AS CITY
FROM PROJECT_DB.STAGING.ORDERS_RAW O
INNER JOIN PROJECT_DB.CLEANED.CUSTOMERS C
    ON TRIM(O.CUSTOMER_ID) = C.CUSTOMER_ID
WHERE O.ORDER_ID IS NOT NULL
  AND TRIM(O.ORDER_ID) <> ''
  AND TRY_TO_DATE(TRIM(O.ORDER_DATE), 'YYYY-MM-DD') IS NOT NULL
  AND O.PRODUCT_NAME IS NOT NULL
  AND TRIM(O.PRODUCT_NAME) <> ''
  AND O.CATEGORY IS NOT NULL
  AND TRIM(O.CATEGORY) <> ''
  AND TRY_TO_NUMBER(O.QUANTITY) > 0
  AND TRY_TO_DECIMAL(O.UNIT_PRICE, 10, 2) > 0
  AND TRY_TO_DECIMAL(O.DISCOUNT_PERCENT, 5, 2)
      BETWEEN 0 AND 100
  AND O.CITY IS NOT NULL
  AND TRIM(O.CITY) <> ''
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY TRIM(O.ORDER_ID)
    ORDER BY TRIM(O.ORDER_ID)
) = 1;

