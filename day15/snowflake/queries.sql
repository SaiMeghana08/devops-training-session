CREATE DATABASE IF NOT EXISTS CUSTOMER_DB;

CREATE SCHEMA IF NOT EXISTS CUSTOMER_DB.STAGING;

USE DATABASE CUSTOMER_DB;
USE SCHEMA STAGING;

CREATE WAREHOUSE IF NOT EXISTS CUSTOMER_WH
WAREHOUSE_SIZE = 'XSMALL'
AUTO_SUSPEND = 60
AUTO_RESUME = TRUE
INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE CUSTOMER_WH;

CREATE TABLE IF NOT EXISTS CUSTOMER_DATA (
    CUSTOMER_ID NUMBER,
    CUSTOMER_NAME VARCHAR(100),
    AGE VARCHAR(20),
    GENDER VARCHAR(20),
    CITY VARCHAR(50),
    SALARY VARCHAR(30)
);

CREATE FILE FORMAT IF NOT EXISTS CUSTOMER_CSV_FORMAT
TYPE = CSV
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
EMPTY_FIELD_AS_NULL = TRUE;

CREATE STAGE IF NOT EXISTS CUSTOMER_STAGE
FILE_FORMAT = CUSTOMER_CSV_FORMAT;

LIST @CUSTOMER_STAGE;

COPY INTO CUSTOMER_DATA
FROM @CUSTOMER_STAGE
FILE_FORMAT = (
    FORMAT_NAME = 'CUSTOMER_CSV_FORMAT'
)
ON_ERROR = 'ABORT_STATEMENT';

SELECT COUNT(*)
FROM CUSTOMER_DATA;

SELECT *
FROM CUSTOMER_DATA;

SELECT
    CUSTOMER_ID,
    COUNT(*) AS TOTAL_COUNT
FROM CUSTOMER_DATA
GROUP BY CUSTOMER_ID
HAVING COUNT(*) > 1;

SELECT *
FROM CUSTOMER_DATA
WHERE CUSTOMER_NAME IS NULL
   OR AGE IS NULL
   OR GENDER IS NULL
   OR CITY IS NULL
   OR SALARY IS NULL;

SELECT *
FROM CUSTOMER_DATA
WHERE TRY_TO_NUMBER(SALARY) < 0;

SELECT
    MIN(TRY_TO_NUMBER(SALARY)) AS MIN_SALARY,
    MAX(TRY_TO_NUMBER(SALARY)) AS MAX_SALARY,
    AVG(TRY_TO_NUMBER(SALARY)) AS AVG_SALARY,
    SUM(TRY_TO_NUMBER(SALARY)) AS TOTAL_SALARY,
    MEDIAN(TRY_TO_NUMBER(SALARY)) AS MEDIAN_SALARY
FROM CUSTOMER_DATA;

SELECT *
FROM CUSTOMER_DATA
WHERE TRY_TO_NUMBER(AGE) <= 0;

SELECT
    CITY,
    AVG(TRY_TO_NUMBER(SALARY)) AS AVG_SALARY
FROM CUSTOMER_DATA
WHERE TRY_TO_NUMBER(SALARY) > 0
GROUP BY CITY;